# ── Email log ─────────────────────────────────────────────────────────────────

def _log_email(usn: str, subject: str, recipient: str,
               status: str, error: str = "", alert_type: str = "absence"):
    """Log sent email to MongoDB email_logs collection."""
    db = get_db()
    db.email_logs.insert_one({
        "usn":        usn,
        "subject":    subject,
        "recipient":  recipient,
        "status":     status,
        "error":      error,
        "alert_type": alert_type,
        "sent_at":    datetime.utcnow(),
    })


