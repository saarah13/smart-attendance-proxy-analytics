# ── Send helpers ──────────────────────────────────────────────────────────────

def _send_email(recipient: str, subject_line: str, html_body: str,
                usn: str, subject: str, alert_type: str) -> bool:
    if not config.EMAIL_SENDER or not config.EMAIL_PASSWORD:
        print("[email_alerts] SMTP credentials not configured — skipping.")
        return False
    if not recipient:
        return False

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject_line
    msg["From"]    = f"{config.EMAIL_SENDER_NAME} <{config.EMAIL_SENDER}>"
    msg["To"]      = recipient
    msg.attach(MIMEText(html_body, "html"))

    try:
        ctx = ssl.create_default_context()
        with smtplib.SMTP(config.SMTP_HOST, config.SMTP_PORT, timeout=10) as srv:
            srv.ehlo(); srv.starttls(context=ctx); srv.login(config.EMAIL_SENDER, config.EMAIL_PASSWORD)
            srv.sendmail(config.EMAIL_SENDER, recipient, msg.as_string())
        _log_email(usn, subject, recipient, "sent", alert_type=alert_type)
        return True
    except Exception as exc:
        _log_email(usn, subject, recipient, "failed", str(exc), alert_type=alert_type)
        print(f"[email_alerts] Failed to send email: {exc}")
        return False


# ── Public API ────────────────────────────────────────────────────────────────

def send_absence_alert(student: dict, subject: str,
                        absence_date: str, consecutive: int) -> bool:
    """Send an HTML absence alert email to the student's parent."""
    name  = student["name"]
    usn   = student["usn"]
    html  = _build_absence_html(name, usn, subject, absence_date, consecutive)
    return _send_email(
        recipient    = student.get("parent_email", ""),
        subject_line = f"[SGBIT] Attendance Alert — {name} absent in {subject}",
        html_body    = html,
        usn          = usn,
        subject      = subject,
        alert_type   = "absence",
    )


def send_low_attendance_alert(student: dict, subject: str,
                               current_pct: float, threshold: int) -> bool:
    """
    Send a LOW ATTENDANCE warning email when the student's attendance %
    drops below the subject threshold.
    """
    name  = student["name"]
    usn   = student["usn"]
    html  = _build_low_attendance_html(name, usn, subject, current_pct, threshold)
    return _send_email(
        recipient    = student.get("parent_email", ""),
        subject_line = f"[SGBIT] ⚠️ Low Attendance Warning — {name} in {subject} ({current_pct:.1f}%)",
        html_body    = html,
        usn          = usn,
        subject      = subject,
        alert_type   = "low_attendance",
    )


def get_email_logs(usn: str = None, limit: int = 50) -> list[dict]:
    """Fetch recent email send logs from MongoDB."""
    db    = get_db()
    query = {"usn": usn} if usn else {}
    logs  = list(db.email_logs.find(query, {"_id": 0}).sort("sent_at", -1).limit(limit))
    return logs
